"""Valid prices and 1D Myerson reconstruction (Definitions 10–11).

For a monotone allocation x : [0:m] → [0:d],

    J_x = {0} ∪ {b in [m] : x(b) != x(b-1)},

written t0 < t1 < … < tk with t0 = 0. A valid price satisfies p(0)=0,
is constant on plateaus of x, and is generated by multipliers h_i with
t_i - 1 <= h_i <= t_i via

    p(b) = sum_{j=1}^{i_b} h_j * (x(t_j) - x(t_{j-1})).
"""

from __future__ import annotations

from typing import Optional, Sequence

import numpy as np
from numpy.typing import ArrayLike, NDArray


def jumps(x_1d: ArrayLike) -> list[int]:
    """Jump set J_x, including the mandatory 0."""
    x = np.asarray(x_1d)
    out = [0]
    for b in range(1, x.shape[0]):
        if x[b] != x[b - 1]:
            out.append(b)
    return out


def is_monotone_1d(x_1d: ArrayLike) -> bool:
    """True iff x is nondecreasing on {0, ..., m}."""
    x = np.asarray(x_1d)
    if x.size <= 1:
        return True
    return bool(np.all(x[1:] >= x[:-1]))


def myerson_price_1d(
    x_1d: ArrayLike,
    h: Optional[Sequence[float]] = None,
) -> NDArray[np.float64]:
    """Reconstruct a valid price vector for a monotone 1D allocation.

    If ``h`` is None, use the left endpoint of each Myerson interval:
    h_i = t_i - 1 for the jump at t_i (i >= 1). The base jump t_0 = 0
    is unpriced. ``h``, when given, is (h_1, ..., h_k).
    """
    x = np.asarray(x_1d, dtype=float)
    m = int(x.shape[0]) - 1
    J = jumps(x)
    k = len(J) - 1
    if h is None:
        h_vals = [float(J[i] - 1) for i in range(1, k + 1)]
    else:
        h_vals = [float(v) for v in h]
        if len(h_vals) != k:
            raise ValueError(
                f"expected {k} multipliers h_1..h_k, got {len(h_vals)}"
            )
    p = np.zeros(m + 1, dtype=np.float64)
    price = 0.0
    for i in range(1, k + 1):
        price += h_vals[i - 1] * (x[J[i]] - x[J[i - 1]])
        start = J[i]
        end = J[i + 1] if i < k else m + 1
        p[start:end] = price
    return p


def is_valid_price_1d(
    x_1d: ArrayLike,
    p_1d: ArrayLike,
    atol: float = 1e-9,
) -> bool:
    """True iff p is a valid price for monotone 1D allocation x."""
    x = np.asarray(x_1d, dtype=float)
    p = np.asarray(p_1d, dtype=float)
    if x.shape != p.shape:
        return False
    if not is_monotone_1d(x):
        return False
    if abs(float(p[0])) > atol:
        return False
    J = jumps(x)
    if J[0] != 0:
        return False
    k = len(J) - 1
    h_vals: list[float] = []
    for i in range(1, k + 1):
        dx = float(x[J[i]] - x[J[i - 1]])
        if abs(dx) <= atol:
            return False
        hi = float(p[J[i]] - p[J[i - 1]]) / dx
        t_i = J[i]
        if hi > t_i + atol or hi < (t_i - 1) - atol:
            return False
        h_vals.append(hi)
    p_rec = myerson_price_1d(x, h=h_vals)
    return bool(np.allclose(p, p_rec, atol=atol, rtol=0.0))
